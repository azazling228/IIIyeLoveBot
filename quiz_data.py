TITLE_RANGES = (
    (95, 100, "Магистр ШУЕ", "title-master"),
    (80, 94, "Безумец", "title-mad"),
    (65, 79, "Знаток", "title-expert"),
    (50, 64, "Почётный зритель", "title-viewer"),
    (0, 49, "Позёр", "title-poser"),
)


def quiz_title(percent):
    for minimum, maximum, title, css_class in TITLE_RANGES:
        if minimum <= percent <= maximum:
            return {"name": title, "class": css_class}
    raise ValueError(f"Quiz score out of range: {percent}")
